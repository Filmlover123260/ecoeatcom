/**
 * Returns the 4 curated daily tips tailored specifically to the given date's day of the week.
 */
export function getDailyTipsForDate(date: Date = new Date()): DailyTipItem[] {
  const dayOfWeek = date.getDay(); // 0 = Sunday, 1 = Monday, ..., 6 = Saturday
  const tipsForDay = allWeeklyTips.filter((t) => t.dayOfWeek === dayOfWeek);
  if (tipsForDay.length > 0) {
    return tipsForDay;
  }
  // Fallback to first 4 tips if not found
  return allWeeklyTips.slice(0, 4);
}

